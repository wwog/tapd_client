//! `$DSH_HOME/profiles/tapd/` rendering.
//!
//! A profile is three files: the manifest (bundle layers), the user patch
//! (our plugin rows, disabled in-box rows, provider config) and pnpm settings
//! the launcher expects to exist. The app rewrites them from settings on every
//! start; the payload's own files are never touched.

use std::fmt::Write as _;
use std::io;
use std::path::Path;

use serde::Serialize;

/// Profile name passed as `dsh --profile tapd`.
pub const PROFILE_NAME: &str = "tapd";

/// Bundle layers: the shared base plus the stdio SDK application.
pub const BUNDLES: [&str; 2] = ["@deepseek-ai/dsh-base", "@deepseek-ai/dsh-sdk-app"];

/// In-box rows we switch off: Office/LibreOffice (huge, unused), the plugin
/// manager (needs pnpm at runtime) and the primary-runtime installer.
pub const DISABLED_ROWS: [&str; 5] = [
    "tool-plugin-manager",
    "office-kit",
    "tool-office",
    "skill-office",
    "workspace-dependencies",
];

/// One mounted plugin. `entry` is the absolute path of its ESM entry inside the
/// extracted payload (`<runtime>/node_modules/@tapd/<name>/index.js`).
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct PluginRow {
    pub id: String,
    pub entry: String,
}

/// One bundled coworker exposed as an agent preset, so the lead can hand it a
/// board task. The child sees the host's global tools plus this overlay: a
/// persona and one extra skill root. Everything is addressed by absolute path
/// because the profile's own module graph has no dependencies.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct CoworkerPreset {
    pub id: String,
    pub name: String,
    pub role: String,
    pub description: String,
    /// Absolute skills root (`<package>/skills`); empty when it ships none.
    pub skills_dir: String,
}

/// ESM entries the preset rows need, resolved inside the extracted payload.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct PresetModules {
    pub registry: String,
    pub declaration: String,
    pub persona: String,
    pub skills: String,
}

#[derive(Clone, Debug, PartialEq, Eq)]
pub struct ProviderModel {
    pub id: String,
    pub name: String,
    pub context_window: u64,
    /// Per-request output cap. `None` keeps the installed catalog's default.
    pub max_tokens: Option<u64>,
    /// Modalities the model accepts (`text`, `image`). Empty keeps the default.
    pub input: Vec<String>,
    /// Reasoning levels in escalation order with their wire values. Empty keeps
    /// the installed catalog's capability.
    pub reasoning: Vec<(String, String)>,
}

/// One custom model route (one settings provider), rendered into `providers`.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct ProviderConfig {
    pub id: String,
    pub display_name: String,
    /// `openai-completions` | `openai-responses` | `anthropic-messages` |
    /// `google-generative-ai` (upstream `api` field).
    pub api: String,
    pub base_url: String,
    /// Env var name resolved through the harness credential seam; absent when
    /// the gateway needs no key.
    pub api_key_env: Option<String>,
    pub models: Vec<ProviderModel>,
}

/// Everything the profile needs, assembled by the caller from settings.
#[derive(Clone, Debug, Default)]
pub struct ProfileSpec {
    pub plugins: Vec<PluginRow>,
    pub providers: Vec<ProviderConfig>,
    /// `agent-team` default; `Some(false)` keeps Team mode off for new sessions.
    pub team_default_enabled: Option<bool>,
    /// Coworkers the lead may spawn by preset id. Empty disables the whole
    /// preset composition (no registry row, no allowlist).
    pub presets: Vec<CoworkerPreset>,
    /// Module entries for the preset rows; required when `presets` is not empty.
    pub preset_modules: Option<PresetModules>,
}

impl ProfileSpec {
    pub fn manifest_json(&self) -> String {
        #[derive(Serialize)]
        struct Manifest<'a> {
            name: String,
            private: bool,
            dependencies: serde_json::Map<String, serde_json::Value>,
            dsh: Inner<'a>,
        }
        #[derive(Serialize)]
        struct Inner<'a> {
            profile: Profile<'a>,
        }
        #[derive(Serialize)]
        struct Profile<'a> {
            bundles: &'a [String],
        }

        let bundles: Vec<String> = BUNDLES.iter().map(|name| name.to_string()).collect();
        let manifest = Manifest {
            name: format!("dsh-profile-{PROFILE_NAME}"),
            private: true,
            dependencies: serde_json::Map::new(),
            dsh: Inner {
                profile: Profile { bundles: &bundles },
            },
        };
        serde_json::to_string_pretty(&manifest).expect("manifest serializes") + "\n"
    }

    pub fn patch_yaml(&self) -> String {
        let mut out = String::new();
        out.push_str("# Generated by TAPD Client. Edits are overwritten on start.\n");

        let presets = self.active_presets();
        if !self.plugins.is_empty() || presets.is_some() {
            out.push_str("- insert:\n");
            for plugin in &self.plugins {
                let _ = writeln!(out, "    - id: {}", quote(&plugin.id));
                let _ = writeln!(out, "      name: {}", quote(&plugin.entry));
            }
            if let Some(modules) = presets {
                self.write_presets(&mut out, modules);
            }
        }

        for row in DISABLED_ROWS {
            let _ = writeln!(out, "- id: {row}\n  disabled: true");
        }

        // The todo tool's config field is required, so the row states it
        // explicitly: team and subagent work runs tasks in parallel, and the
        // description must then let the model mark several `in_progress`.
        out.push_str("- id: tool-todo\n  config:\n    allowParallelInProgress: true\n");

        if let Some(enabled) = self.team_default_enabled {
            let _ = writeln!(out, "- id: agent-team\n  config:\n    defaultEnabled: {enabled}");
        }

        // The spawn tool's `agent_preset` enum is exactly the allowlist, so the
        // lead can name a coworker when it starts a child. `provider` is
        // required: a config patch replaces the whole row config.
        if presets.is_some() {
            out.push_str("- id: tool-subagent\n  config:\n    provider: spawn\n    toolName: subagent\n    allowedAgentPresets:\n");
            for preset in &self.presets {
                let _ = writeln!(out, "      - {}", quote(&preset.id));
            }
        }

        if !self.providers.is_empty() {
            out.push_str("- id: llm-pi-ai\n  config:\n    providers:\n");
            for provider in &self.providers {
                let _ = writeln!(out, "      {}:", quote(&provider.id));
                let _ = writeln!(out, "        displayName: {}", quote(&provider.display_name));
                let _ = writeln!(out, "        api: {}", quote(&provider.api));
                let _ = writeln!(out, "        baseURL: {}", quote(&provider.base_url));
                if let Some(env) = &provider.api_key_env {
                    let _ = writeln!(out, "        apiKeyEnv: {}", quote(env));
                }
                if !provider.models.is_empty() {
                    out.push_str("        models:\n");
                    for model in &provider.models {
                        let _ = writeln!(out, "          - id: {}", quote(&model.id));
                        let _ = writeln!(out, "            name: {}", quote(&model.name));
                        let _ = writeln!(out, "            contextWindow: {}", model.context_window);
                        // Everything below is optional: leaving it out lets the
                        // installed catalog answer instead.
                        if let Some(max_tokens) = model.max_tokens {
                            let _ = writeln!(out, "            maxTokens: {max_tokens}");
                        }
                        if !model.input.is_empty() {
                            let list = model
                                .input
                                .iter()
                                .map(|modality| format!("'{modality}'"))
                                .collect::<Vec<_>>()
                                .join(", ");
                            let _ = writeln!(out, "            input: [{list}]");
                        }
                        if !model.reasoning.is_empty() {
                            out.push_str("            reasoningEfforts:\n");
                            for (level, wire) in &model.reasoning {
                                // Only `off` may stay valueless: YAML null is the
                                // documented spelling, while '' is rejected.
                                if wire.is_empty() {
                                    let _ = writeln!(out, "              {level}:");
                                } else {
                                    let _ =
                                        writeln!(out, "              {level}: {}", quote(wire));
                                }
                            }
                        }
                    }
                }
            }
        }

        out
    }

    /// Preset rows render only when the payload ships their modules; a stripped
    /// payload then keeps the plain subagent path instead of a broken profile.
    fn active_presets(&self) -> Option<&PresetModules> {
        if self.presets.is_empty() {
            return None;
        }
        self.preset_modules.as_ref()
    }

    /// Registry row plus one declaration per coworker, appended inside the
    /// insert block. A preset is an overlay on the host's global composition:
    /// its own persona and one extra skill root, no tools of its own.
    fn write_presets(&self, out: &mut String, modules: &PresetModules) {
        let _ = writeln!(out, "    - id: 'agent-preset-registry'");
        let _ = writeln!(out, "      name: {}", quote(&modules.registry));
        let _ = writeln!(out, "      config:");
        // `default` is required by the registry schema. Nothing here resolves
        // it without an id (the SDK creator composes no preset), so it names
        // the first coworker only to stay valid.
        let _ = writeln!(out, "        default: {}", quote(&self.presets[0].id));
        for (index, preset) in self.presets.iter().enumerate() {
            let _ = writeln!(out, "    - id: {}", quote(&format!("preset-{}", preset.id)));
            let _ = writeln!(out, "      name: {}", quote(&modules.declaration));
            let _ = writeln!(out, "      config:");
            let _ = writeln!(out, "        id: {}", quote(&preset.id));
            let _ = writeln!(out, "        name: {}", quote(&preset.name));
            if !preset.description.trim().is_empty() {
                let _ = writeln!(out, "        description: {}", quote(preset.description.trim()));
            }
            let _ = writeln!(out, "        order: {}", index + 1);
            let _ = writeln!(out, "        plugins:");
            let _ = writeln!(out, "          - id: persona");
            let _ = writeln!(out, "            name: {}", quote(&modules.persona));
            let _ = writeln!(out, "            config:");
            let _ = writeln!(out, "              prefix: {}", quote(&persona_text(preset)));
            if !preset.skills_dir.is_empty() {
                // A distinct provider name keeps the global skill roots
                // visible (same-name providers shadow instead of merging).
                let _ = writeln!(out, "          - id: coworker-skills");
                let _ = writeln!(out, "            name: {}", quote(&modules.skills));
                let _ = writeln!(out, "            config:");
                let _ = writeln!(
                    out,
                    "              providerName: {}",
                    quote(&format!("coworker-{}", preset.id))
                );
                let _ = writeln!(out, "              customSkillDirs:");
                let _ = writeln!(out, "                - {}", quote(&preset.skills_dir));
            }
        }
    }

    /// pnpm settings the launcher expects in a profile directory.
    pub fn pnpm_workspace() -> &'static str {
        "packages:\n  - .\n\nnodeLinker: hoisted\nautoInstallPeers: false\n"
    }

    /// Writes all three files into `dir` (creating it if needed).
    pub fn write(&self, dir: &Path) -> io::Result<()> {
        std::fs::create_dir_all(dir)?;
        std::fs::write(dir.join("package.json"), self.manifest_json())?;
        std::fs::write(dir.join("cordis.patch.yml"), self.patch_yaml())?;
        std::fs::write(dir.join("pnpm-workspace.yaml"), Self::pnpm_workspace())?;
        Ok(())
    }
}

/// Single-quoted YAML scalar. Paths and ids may contain spaces, `#`, `:` or
/// backslashes, so every interpolated string goes through here.
fn quote(value: &str) -> String {
    format!("'{}'", value.replace('\'', "''"))
}

/// Prompt text for one preset child. It is model input, not app copy, so it is
/// intentionally not localized: the coworker package speaks the team's language.
fn persona_text(preset: &CoworkerPreset) -> String {
    let mut text = String::from("你是团队里的");
    text.push('「');
    text.push_str(preset.role.trim());
    text.push('」');
    text.push_str(preset.name.trim());
    let description = preset.description.trim();
    if !description.is_empty() {
        text.push('：');
        text.push_str(description);
    }
    // Manifests often end their description with a full stop; adding one more
    // would read as "。。". An empty description still needs the separator.
    if !text.ends_with(['。', '！', '？', '.', '!', '?', '；', ';']) {
        text.push('。');
    }
    text.push_str("需要时先用 skill 工具加载相关技能包，再开始工作。");
    text
}

#[cfg(test)]
mod tests {
    use super::*;

    fn spec() -> ProfileSpec {
        ProfileSpec {
            plugins: vec![PluginRow {
                id: "tapd-tools".into(),
                entry: "/Users/me/Library/Application Support/tapd/dsh/0.2.2-rc.3/node_modules/@tapd/plugin-tools/index.js".into(),
            }],
            providers: vec![ProviderConfig {
                id: "acme-gateway".into(),
                display_name: "Acme Gateway".into(),
                api: "openai-completions".into(),
                base_url: "https://gateway.example/v1".into(),
                api_key_env: Some("ACME_API_KEY".into()),
                models: vec![ProviderModel {
                    id: "acme-think".into(),
                    name: "acme-think".into(),
                    context_window: 262_144,
                    max_tokens: None,
                    input: vec!["text".into()],
                    reasoning: Vec::new(),
                }],
            }],
            team_default_enabled: Some(false),
            presets: Vec::new(),
            preset_modules: None,
        }
    }

    #[test]
    fn manifest_lists_the_shipped_bundles() {
        let manifest = spec().manifest_json();
        assert!(manifest.contains("\"@deepseek-ai/dsh-base\""));
        assert!(manifest.contains("\"@deepseek-ai/dsh-sdk-app\""));
        assert!(manifest.contains("\"name\": \"dsh-profile-tapd\""));
    }

    #[test]
    fn patch_quotes_paths_and_disables_inbox_rows() {
        let yaml = spec().patch_yaml();
        assert!(yaml.contains(
            "      name: '/Users/me/Library/Application Support/tapd/dsh/0.2.2-rc.3/node_modules/@tapd/plugin-tools/index.js'"
        ));
        assert!(yaml.contains("- id: tool-plugin-manager\n  disabled: true"));
        // The todo tool mounts with parallel in-progress tasks allowed: team /
        // subagent work legitimately runs several tasks at once.
        assert!(yaml.contains(
            "- id: tool-todo\n  config:\n    allowParallelInProgress: true\n"
        ));
        assert!(yaml.contains("- id: agent-team\n  config:\n    defaultEnabled: false"));
        assert!(yaml.contains("        apiKeyEnv: 'ACME_API_KEY'"));
        assert!(yaml.contains("            contextWindow: 262144"));
        assert!(yaml.contains("            input: ['text']"));
    }

    #[test]
    fn every_enabled_route_lands_in_providers() {
        let mut spec = spec();
        spec.providers.push(ProviderConfig {
            id: "second".into(),
            display_name: "Second".into(),
            api: "anthropic-messages".into(),
            base_url: "https://second.example".into(),
            api_key_env: None,
            models: vec![ProviderModel {
                id: "fast".into(),
                name: "fast".into(),
                context_window: 128_000,
                max_tokens: Some(8_192),
                input: vec!["text".into(), "image".into()],
                reasoning: vec![
                    ("low".into(), "low".into()),
                    ("high".into(), "high".into()),
                ],
            }],
        });
        let yaml = spec.patch_yaml();
        assert!(yaml.contains("      'acme-gateway':"));
        assert!(yaml.contains("      'second':"));
        assert!(yaml.contains("        api: 'anthropic-messages'"));
        assert!(yaml.contains("            maxTokens: 8192"));
        assert!(yaml.contains("            input: ['text', 'image']"));
        assert!(yaml.contains(
            "            reasoningEfforts:\n              low: 'low'\n              high: 'high'\n"
        ));
        // A route with no credential names none.
        assert_eq!(yaml.matches("apiKeyEnv:").count(), 1);
    }

    #[test]
    fn absent_per_model_fields_are_omitted() {
        let yaml = spec().patch_yaml();
        assert!(!yaml.contains("maxTokens:"));
        assert!(!yaml.contains("reasoningEfforts:"));
    }

    #[test]
    fn empty_spec_still_renders_valid_layers() {
        let yaml = ProfileSpec::default().patch_yaml();
        assert!(!yaml.contains("- insert:"));
        assert!(!yaml.contains("llm-pi-ai"));
        assert!(yaml.contains("- id: office-kit\n  disabled: true"));
    }

    #[test]
    fn single_quotes_are_doubled() {
        assert_eq!(quote("a'b"), "'a''b'");
    }

    fn preset_spec() -> ProfileSpec {
        let mut spec = spec();
        spec.presets = vec![
            CoworkerPreset {
                id: "author".into(),
                name: "Author".into(),
                role: "程序员".into(),
                description: "一起写代码".into(),
                skills_dir: "/app/Contents/Resources/coworker/author/skills".into(),
            },
            CoworkerPreset {
                id: "reviewer".into(),
                name: "Reviewer".into(),
                role: "审查者".into(),
                description: String::new(),
                skills_dir: String::new(),
            },
        ];
        spec.preset_modules = Some(PresetModules {
            registry: "/rt/node_modules/@deepseek-ai/dsh-agent-preset-registry/lib/index.js".into(),
            declaration: "/rt/node_modules/@deepseek-ai/dsh-agent-preset/lib/index.js".into(),
            persona: "/rt/node_modules/@deepseek-ai/dsh-persona/lib/index.js".into(),
            skills: "/rt/node_modules/@deepseek-ai/dsh-skill-filesystem/lib/index.js".into(),
        });
        spec
    }

    #[test]
    fn presets_add_a_registry_declaration_and_allowlist() {
        let yaml = preset_spec().patch_yaml();
        assert!(yaml.contains("    - id: 'agent-preset-registry'"));
        assert!(yaml.contains("        default: 'author'"));
        assert!(yaml.contains("    - id: 'preset-author'"));
        assert!(yaml.contains("        id: 'author'"));
        assert!(yaml.contains(
            "              prefix: '你是团队里的「程序员」Author：一起写代码。需要时先用 skill 工具加载相关技能包，再开始工作。'"
        ));
        assert!(yaml.contains("              providerName: 'coworker-author'"));
        assert!(yaml.contains("                - '/app/Contents/Resources/coworker/author/skills'"));
        assert!(yaml.contains(
            "- id: tool-subagent\n  config:\n    provider: spawn\n    toolName: subagent\n    allowedAgentPresets:\n      - 'author'\n      - 'reviewer'"
        ));
        // A coworker without skills gets no provider row, and an empty
        // description is omitted rather than rendered as an empty scalar.
        assert_eq!(yaml.matches("providerName:").count(), 1);
        assert_eq!(yaml.matches("description:").count(), 1);
    }

    #[test]
    fn persona_text_does_not_double_the_full_stop() {
        let preset = CoworkerPreset {
            id: "author".into(),
            name: "Author".into(),
            role: "程序员".into(),
            description: "一起写代码。".into(),
            skills_dir: String::new(),
        };
        assert!(persona_text(&preset).contains("一起写代码。需要时"));
        let bare = CoworkerPreset {
            description: String::new(),
            ..preset
        };
        assert!(persona_text(&bare).contains("Author。需要时"));
    }

    #[test]
    fn presets_without_modules_render_nothing() {
        let mut spec = spec();
        spec.presets = preset_spec().presets;
        let yaml = spec.patch_yaml();
        assert!(!yaml.contains("agent-preset"));
        assert!(!yaml.contains("tool-subagent"));
    }
}
