/// One-time pairing codes expire after ten minutes (single use on top).
const PAIRING_TTL_SECS: i64 = 600;

// ---------------------------------------------------------------------------
// Server runtime state
// ---------------------------------------------------------------------------

/// One-time pairing code: generated by `companion_pairing_code`, consumed by
/// the pair route. Single use is enforced by removing it on a successful match.
pub(crate) struct PairingCode {
    pub(crate) code: String,
    pub(crate) expires_at: chrono::DateTime<chrono::Utc>,
}

/// Runtime state of the companion server, guarded by the `AppState` mutex.
#[derive(Default)]
pub struct CompanionRuntime {
    /// LAN port while the accept loop is alive.
    pub port: Option<u16>,
    /// Serve task; aborted when the companion is disabled and on app exit.
    pub task: Option<tauri::async_runtime::JoinHandle<()>>,
    /// Current one-time pairing code, if one has been generated.
    pub(crate) pairing: Option<PairingCode>,
}

impl CompanionRuntime {
    /// Consumes a valid one-time pairing code. The pair route calls this under
    /// the runtime lock, so validation and invalidation share one critical
    /// section and a code can never be used twice, even by concurrent pairs.
    pub(super) fn consume_pairing_code(
        &mut self,
        code: &str,
        now: chrono::DateTime<chrono::Utc>,
    ) -> bool {
        match &self.pairing {
            Some(pairing) if pairing.code == code && pairing.expires_at > now => {
                self.pairing = None;
                true
            }
            _ => false,
        }
    }
}

/// Per-request context handed to every route handler. Private to the
/// `companion` tree: only its own submodules build and extract it.
#[derive(Clone)]
struct CompanionCtx {
    pub(super) app: AppHandle,
    pub(super) state: SharedState,
    /// Pairing rate limiter; one instance per server run.
    pub(super) pair_limiter: Arc<Mutex<RateLimiter>>,
    /// Feature-proxy rate limiter; one instance per server run.
    pub(super) feature_limiter: Arc<Mutex<RateLimiter>>,
}

/// Starts the companion LAN server, recording its port and task handle.
///
/// The bind happens before the serve task is spawned so a port failure
/// surfaces to the caller (settings UI) instead of dying in a detached task.
/// Already running is a no-op: enabling twice must not bind a second port.
pub async fn start(app: AppHandle, state: SharedState) -> Result<(), String> {
    if state.companion.lock().expect("companion lock").task.is_some() {
        return Ok(());
    }

    let listener = tokio::net::TcpListener::bind(("0.0.0.0", 0))
        .await
        .map_err(|error| error.to_string())?;
    let port = listener
        .local_addr()
        .map_err(|error| error.to_string())?
        .port();

    let mut runtime = state.companion.lock().expect("companion lock");
    if runtime.task.is_some() {
        // A concurrent start won the race; drop our listener and keep theirs.
        return Ok(());
    }
    let handle = tauri::async_runtime::spawn({
        let app = app.clone();
        let state = state.clone();
        async move {
            if let Err(error) = serve(listener, app, state).await {
                tracing::error!(%error, "companion server stopped");
            }
        }
    });
    runtime.task = Some(handle);
    runtime.port = Some(port);
    tracing::info!(port, "companion server listening");
    Ok(())
}

/// Stops the companion server and clears its runtime state (task, port and
/// the outstanding pairing code, whose URL is useless without the server).
pub fn stop(state: &SharedState) {
    let mut runtime = state.companion.lock().expect("companion lock");
    if let Some(task) = runtime.task.take() {
        task.abort();
    }
    runtime.port = None;
    runtime.pairing = None;
}

async fn serve(
    listener: tokio::net::TcpListener,
    app: AppHandle,
    state: SharedState,
) -> Result<(), String> {
    let ctx = CompanionCtx {
        app,
        state,
        pair_limiter: Arc::new(Mutex::new(RateLimiter::default())),
        feature_limiter: Arc::new(Mutex::new(rate_limiter())),
    };

    let router = Router::new()
        .route("/companion/api/pair", post(pair))
        .route("/companion/api/state", get(api_state))
        .route("/companion/api/workspaces", get(api_workspaces))
        .route("/companion/api/bugs", post(api_bugs))
        .route("/companion/api/bug", get(api_bug_detail))
        .route("/companion/api/notifications", get(api_notifications))
        .route("/companion/api/media", get(api_media))
        .route("/companion/api/feature", post(api_feature))
        .fallback(static_fallback)
        .with_state(ctx);

    axum::serve(
        listener,
        router.into_make_service_with_connect_info::<SocketAddr>(),
    )
    .await
    .map_err(|error| error.to_string())
}

// ---------------------------------------------------------------------------
// Response envelope
// ---------------------------------------------------------------------------

pub(super) fn ok_data<T: Serialize>(data: T) -> Response {
    (StatusCode::OK, Json(json!({ "ok": true, "data": data }))).into_response()
}

pub(super) fn err_data(status: StatusCode, code: &str, error: &str) -> Response {
    (
        status,
        Json(json!({ "ok": false, "code": code, "error": error })),
    )
        .into_response()
}

/// A desktop-side command core failed (TAPD request, parse, …). The message is
/// the same user-facing text the desktop UI would show.
pub(super) fn upstream_error(error: String) -> Response {
    (
        StatusCode::BAD_GATEWAY,
        Json(json!({ "ok": false, "code": "upstream", "error": error })),
    )
        .into_response()
}

