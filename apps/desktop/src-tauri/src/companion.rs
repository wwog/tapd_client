/// A device is "online" while its last heartbeat is younger than this. The
/// phone beats every 20s, so 60s tolerates two missed beats / background
/// timer throttling without flapping.
pub(crate) const PRESENCE_ONLINE_SECS: i64 = 60;
/// Emitted right after a phone consumes a pairing code (the desktop dialog
/// switches from "waiting" to "connected" without waiting for a poll).
pub(crate) const PAIRED_EVENT: &str = "companion://paired";
/// Emitted on every heartbeat so the dialog's device list stays live.
pub(crate) const PRESENCE_EVENT: &str = "companion://presence";

// ---------------------------------------------------------------------------
// Server runtime state
// ---------------------------------------------------------------------------

/// One-time pairing code: generated by `companion_pairing_code`, consumed by
/// the pair route. Single use is enforced by removing it on a successful
/// match. There is no time-based expiry: a code stays valid until it is used,
/// replaced by a newly generated one, or the app exits.
pub(crate) struct PairingCode {
    pub(crate) code: String,
}

/// Last heartbeat of one paired device. In-memory only: presence is a live
/// fact, not something worth persisting across launches.
pub(crate) struct Presence {
    pub(crate) last_seen: chrono::DateTime<chrono::Utc>,
}

/// Whether a heartbeat at `last_seen` still counts as online at `now`.
pub(super) fn presence_is_online(
    last_seen: chrono::DateTime<chrono::Utc>,
    now: chrono::DateTime<chrono::Utc>,
) -> bool {
    now.signed_duration_since(last_seen) < chrono::Duration::seconds(PRESENCE_ONLINE_SECS)
}

/// Runtime state of the companion server, guarded by the `AppState` mutex.
#[derive(Default)]
pub struct CompanionRuntime {
    /// LAN port while the accept loop is alive.
    pub port: Option<u16>,
    /// Serve task; aborted when the companion is disabled and on app exit.
    pub task: Option<tauri::async_runtime::JoinHandle<()>>,
    /// Current one-time pairing code, if one has been generated.
    pub(crate) pairing: Option<PairingCode>,
    /// cloudflared Quick Tunnel process and its last known state.
    pub(crate) tunnel: tunnel::TunnelRuntime,
    /// Cached detection result; refreshed by `companion_cloudflared_check`.
    pub(crate) cloudflared: Option<tunnel::CloudflaredInfo>,
    /// Device id → last heartbeat, for the "online" dot in the dialog.
    pub(crate) presence: HashMap<String, Presence>,
    /// Bumped whenever a paired device loses access (unpair, server stop).
    /// Live terminal sockets compare it on every ping and close themselves:
    /// HTTP auth only happens before the upgrade.
    pub(crate) revoked: Arc<tokio::sync::Notify>,
    pub(crate) revoked_generation: Arc<std::sync::atomic::AtomicU64>,
}

impl CompanionRuntime {
    /// Wakes every live companion socket so it can re-check its authorization.
    /// Callers hold the runtime lock, so a socket that reads the generation
    /// after this call always observes the bump.
    pub(super) fn revoke_live_sockets(&self) {
        self.revoked_generation
            .fetch_add(1, std::sync::atomic::Ordering::SeqCst);
        self.revoked.notify_waiters();
    }

    /// Consumes a valid one-time pairing code. The pair route calls this under
    /// the runtime lock, so validation and invalidation share one critical
    /// section and a code can never be used twice, even by concurrent pairs.
    pub(super) fn consume_pairing_code(&mut self, code: &str) -> bool {
        match &self.pairing {
            Some(pairing) if pairing.code == code => {
                self.pairing = None;
                true
            }
            _ => false,
        }
    }
}

/// Per-request context handed to every route handler. Private to the
/// `companion` tree: only its own submodules build and extract it.
#[derive(Clone)]
struct CompanionCtx {
    pub(super) app: AppHandle,
    pub(super) state: SharedState,
    /// Pairing rate limiter; one instance per server run.
    pub(super) pair_limiter: Arc<Mutex<RateLimiter>>,
    /// Feature-proxy rate limiter; one instance per server run.
    pub(super) feature_limiter: Arc<Mutex<RateLimiter>>,
}

/// Starts the companion LAN server, recording its port and task handle.
///
/// The bind happens before the serve task is spawned so a port failure
/// surfaces to the caller (settings UI) instead of dying in a detached task.
/// Already running is a no-op: enabling twice must not bind a second port.
pub async fn start(app: AppHandle, state: SharedState) -> Result<(), String> {
    if state.companion.lock().expect("companion lock").task.is_some() {
        return Ok(());
    }

    // A tunnel from a previous server instance points at a dead port.
    tunnel::stop(&state, &app);

    let listener = tokio::net::TcpListener::bind(("0.0.0.0", 0))
        .await
        .map_err(|error| error.to_string())?;
    let port = listener
        .local_addr()
        .map_err(|error| error.to_string())?
        .port();

    let mut runtime = state.companion.lock().expect("companion lock");
    if runtime.task.is_some() {
        // A concurrent start won the race; drop our listener and keep theirs.
        return Ok(());
    }
    let handle = tauri::async_runtime::spawn({
        let app = app.clone();
        let state = state.clone();
        async move {
            if let Err(error) = serve(listener, app, state).await {
                tracing::error!(%error, "companion server stopped");
            }
        }
    });
    runtime.task = Some(handle);
    runtime.port = Some(port);
    tracing::info!(port, "companion server listening");
    Ok(())
}

/// Stops the companion server, its tunnel and all live presence. The
/// outstanding pairing code dies with the server: its URL no longer answers.
pub fn stop(app: &AppHandle, state: &SharedState) {
    {
        let mut runtime = state.companion.lock().expect("companion lock");
        // Upgraded WebSockets outlive the accept loop; wake them so a disabled
        // server cannot leave a phone attached to a live shell.
        runtime.revoke_live_sockets();
        if let Some(task) = runtime.task.take() {
            task.abort();
        }
        runtime.port = None;
        runtime.pairing = None;
        runtime.presence.clear();
    }
    tunnel::stop(state, app);
}

async fn serve(
    listener: tokio::net::TcpListener,
    app: AppHandle,
    state: SharedState,
) -> Result<(), String> {
    let ctx = CompanionCtx {
        app,
        state,
        pair_limiter: Arc::new(Mutex::new(RateLimiter::default())),
        feature_limiter: Arc::new(Mutex::new(rate_limiter())),
    };

    let router = Router::new()
        .route("/companion/api/pair", post(pair))
        .route("/companion/api/heartbeat", post(heartbeat))
        .route("/companion/api/state", get(api_state))
        .route("/companion/api/workspaces", get(api_workspaces))
        .route("/companion/api/members", get(api_members))
        .route("/companion/api/bugs", post(api_bugs))
        .route("/companion/api/bug", get(api_bug_detail))
        .route("/companion/api/bug/comment", post(api_bug_comment))
        .route("/companion/api/bug/update-field", post(api_bug_update_field))
        .route("/companion/api/bug/transitions", get(api_bug_transitions))
        .route("/companion/api/bug/transition", post(api_bug_transition))
        .route("/companion/api/bug/claim", post(api_bug_claim))
        .route("/companion/api/notifications", get(api_notifications))
        .route("/companion/api/media", get(api_media))
        .route("/companion/api/devices", get(api_devices))
        .route(
            "/companion/api/devices/permission",
            post(api_device_permission),
        )
        .route("/companion/api/devices/unpair", post(api_device_unpair))
        .route("/companion/api/files", get(api_files))
        .route("/companion/api/file", get(api_file))
        .route("/companion/api/file/raw", get(api_file_raw))
        .route(
            "/companion/api/file/write",
            get(api_file_write_state).post(api_file_write),
        )
        .route(
            "/companion/api/file/write-setting",
            post(api_file_write_setting),
        )
        .route("/companion/api/feature", post(api_feature))
        .route("/companion/api/terminal/ws", get(ws_terminal))
        // Text edits carry up to 2 MiB; JSON escaping plus the request envelope
        // needs headroom above that.
        .layer(DefaultBodyLimit::max(8 * 1024 * 1024))
        .fallback(static_fallback)
        .with_state(ctx);

    axum::serve(
        listener,
        router.into_make_service_with_connect_info::<SocketAddr>(),
    )
    .await
    .map_err(|error| error.to_string())
}

// ---------------------------------------------------------------------------
// Response envelope
