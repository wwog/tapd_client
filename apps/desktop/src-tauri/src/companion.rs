/// First private IPv4 of this machine, for the pairing URL. Home Wi-Fi ranges
/// win (`192.168` before `10.` before `172.16–31`); VPN/virtual adapters
/// usually expose non-private addresses and are skipped. `None` means the
/// settings card shows its "no LAN address" error state.
pub fn lan_ipv4() -> Option<IpAddr> {
    let interfaces = local_ip_address::list_afinet_netifas().ok()?;
    let mut candidates: Vec<Ipv4Addr> = interfaces
        .into_iter()
        .filter_map(|(_, ip)| match ip {
            IpAddr::V4(v4) if is_private_ipv4(v4) => Some(v4),
            _ => None,
        })
        .collect();
    candidates.sort_by_key(|ip| private_rank(*ip));
    candidates.first().map(|ip| IpAddr::V4(*ip))
}

fn is_private_ipv4(ip: Ipv4Addr) -> bool {
    match ip.octets() {
        [192, 168, ..] | [10, ..] => true,
        [172, second, ..] => (16..=31).contains(&second),
        _ => false,
    }
}

/// Preference order among the private ranges.
fn private_rank(ip: Ipv4Addr) -> u8 {
    match ip.octets() {
        [192, 168, ..] => 0,
        [10, ..] => 1,
        [172, second, ..] if (16..=31).contains(&second) => 2,
        _ => 3,
    }
}

