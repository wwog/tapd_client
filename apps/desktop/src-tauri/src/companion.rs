//! Mobile companion: a LAN HTTP server the phone pairs with and reads from.
//!
//! The phone is a pure rendering terminal: every data fetch runs through the
//! same desktop command cores the UI uses (`commands::*_core`, `observe=false`
//! so phone refreshes never silence desktop notifications), bypassing the MCP
//! tool layer. Pairing exchanges a one-time 10-minute code for a 64-hex
//! session token; the config only stores its SHA-256.
//!
//! Route contract: every API answer is `{ ok: true, data }` or
//! `{ ok: false, code, error }`. Static assets come from the embedded
//! `dist-companion/` SPA (debug builds read the folder from disk).
//!
//! Module layout:
//! - `pairing` — the pair route, session auth guards and per-IP rate limiting.
//! - `assets` — embedded SPA static file serving.
//! - `api` — read endpoints (state / workspaces / bugs / notifications / media)
//!   plus the members directory and the bug write endpoints (comment /
//!   update-field / transitions / transition / claim), which run the same
//!   desktop command cores the bug detail panel uses.
//! - `feature` — whitelisted proxy to the desktop `feature_command` surface.
//! - `tunnel` — cloudflared Quick Tunnel detection, lifecycle and URL parsing.
//!
//! Every `#[tauri::command]` stays in this module because `lib.rs` registers
//! it as `companion::<name>` and the handler macro resolves the generated
//! wrapper through the same path (same rule as `commands.rs`).

