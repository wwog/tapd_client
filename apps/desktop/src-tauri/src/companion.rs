/// Updates one device's management permission. Returns false when the id is
/// unknown so callers can surface a not-found error.
pub(super) fn set_device_manage(
    devices: &mut [CompanionDevice],
    device_id: &str,
    can_manage: bool,
) -> bool {
    match devices.iter_mut().find(|device| device.id == device_id) {
        Some(device) => {
            device.can_manage = can_manage;
            true
        }
        None => false,
    }
}

/// Removes one device by id, reporting whether a row was removed.
pub(super) fn remove_device(devices: &mut Vec<CompanionDevice>, device_id: &str) -> bool {
    let before = devices.len();
    devices.retain(|device| device.id != device_id);
    devices.len() != before
}

/// Toggles one device's management permission from the desktop settings UI.
#[tauri::command]
pub fn companion_set_device_manage(
    state: tauri::State<'_, SharedState>,
    device_id: String,
    can_manage: bool,
) -> Result<(), String> {
    let updated = state
        .update_config(|config| {
            set_device_manage(&mut config.companion.devices, &device_id, can_manage)
        })
        .map_err(|error| error.to_string())?;
    if updated {
        Ok(())
    } else {
        Err(tr("companion.devices.notfound").to_string())
    }
}

/// Removes a paired device; its session token stops authorizing immediately.
#[tauri::command]
pub fn companion_unpair(state: tauri::State<'_, SharedState>, device_id: String) -> Result<(), String> {
    let removed = state
        .update_config(|config| remove_device(&mut config.companion.devices, &device_id))
        .map_err(|error| error.to_string())?;
    if removed {
        state
            .companion
            .lock()
            .expect("companion lock")
            .presence
            .remove(&device_id);
    }
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;
    use chrono::{Duration, Utc};

    #[test]
    fn presence_online_window_is_sixty_seconds() {
        let now = Utc::now();
        assert!(presence_is_online(now - Duration::seconds(59), now));
        assert!(!presence_is_online(now - Duration::seconds(60), now));
        assert!(!presence_is_online(now - Duration::seconds(61), now));
    }

    fn device(id: &str, can_manage: bool) -> CompanionDevice {
        CompanionDevice {
            id: id.to_string(),
            name: id.to_string(),
            token_hash: format!("hash-{id}"),
            paired_at: "2026-11-13T00:00:00+00:00".to_string(),
            can_manage,
        }
    }

    #[test]
    fn set_device_manage_updates_only_the_target() {
        let mut devices = vec![device("a", true), device("b", false)];

        assert!(set_device_manage(&mut devices, "b", true));
        assert!(devices[0].can_manage);
        assert!(devices[1].can_manage);

        assert!(!set_device_manage(&mut devices, "missing", true));
    }

    #[test]
    fn remove_device_reports_whether_a_row_was_removed() {
        let mut devices = vec![device("a", true), device("b", false)];

        assert!(remove_device(&mut devices, "a"));
        assert_eq!(devices.len(), 1);
        assert_eq!(devices[0].id, "b");
        assert!(!remove_device(&mut devices, "missing"));
    }
}
